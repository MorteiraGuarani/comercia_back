-- Columnas de negocio con los nombres y tipos originales. id y empresa_id
-- son técnicos, igual que en productos. Las referencias de ERP son lógicas:
-- no se rechazan cargas parciales ni se inventan catálogos para los valores -1.

CREATE TABLE "tbl_ocrd" (
  "id" BIGSERIAL PRIMARY KEY,
  "empresa_id" INTEGER NOT NULL REFERENCES "empresas"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
