  "U_Latitud" VARCHAR(30),
  "U_Longitud" VARCHAR(30),
  "U_jCANAL" VARCHAR(50),
  "U_jSUBCANAL" VARCHAR(50)
);
CREATE UNIQUE INDEX "uq_tbl_ocrd_cardcode" ON "tbl_ocrd" ("empresa_id", "CardCode") NULLS NOT DISTINCT;
CREATE INDEX "idx_tbl_ocrd_cardname" ON "tbl_ocrd" ("empresa_id", "CardName");
CREATE INDEX "idx_tbl_ocrd_groupcode" ON "tbl_ocrd" ("empresa_id", "GroupCode");
